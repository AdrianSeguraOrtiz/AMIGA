def build_comparison_archive(output,root=None):
    """Deposit the already completed benchmark inputs, figures and predictions."""
    from .spec import REPO,SOURCE
    root=Path(root or REPO).resolve()
    output=Path(output).resolve()
    if output.exists(): raise ValueError('Use a new comparison deposit destination')
    c=json.loads((root/SOURCE).read_text())
    groups={'inputs':{},'comparison-and-figures':{},'held-out-predictions':{}}
    def add(group,path):
        path=Path(path)
        groups[group][path.relative_to(root).as_posix()]=path
    for case,info in c['split_contract']['cases'].items():
        add('inputs',root/info['data_path'])
        add('inputs',root/f'docs/experiments/contracts/{case}_feature_columns.json')
    add('inputs',root/'docs/experiments/groups/topology_groups.json')
    add('inputs',root/SOURCE)
    figures=root/'experiments/reports/figures-002'
    report,_=verify_manifest(figures/'manifest.json')
    for name,digest in report['inputs_sha256'].items():
        path=Path(name)
        if not path.is_relative_to(root) or sha256(path)!=digest:
            raise ValueError('Figure input identity differs')
        add('comparison-and-figures',path)
    for path in figures.rglob('*'):
        if path.is_file(): add('comparison-and-figures',path)
    for relative in ('experiments/outer-evaluation/runs/evaluation-001',
                     'experiments/top5-classification/full-001/outer-run',
                     'experiments/top10-classification/full-001/outer-run'):
        run=root/relative
        for name in ('manifest.json','contract.json','plan.json','state.json'):
            add('held-out-predictions',run/name)
        for job in json.loads((run/'plan.json').read_text()):
            if job.get('arm') not in {'ranking','reg_aupr','clf_top05','clf_top10','clf_top20'} and job['stage']!='baselines':
                continue
            completed=[]
            for path in (run/'jobs'/job['id']).glob('attempt-*/result.json'):
                report=json.loads(path.read_text())
                if report.get('status')=='complete': completed.append((path,report))
            if len(completed)!=1: raise ValueError('Expected exactly one successful prediction job')
            path,report=completed[0]
            if report.get('job')!=job: raise ValueError('Prediction job identity differs')
            add('held-out-predictions',path)
            for name,digest in report['artifacts'].items():
                portable(name)
                artifact=path.parent/name
                if sha256(artifact)!=digest: raise ValueError('Prediction artifact identity differs')
                add('held-out-predictions',artifact)
    output.parent.mkdir(parents=True,exist_ok=True)
    with TemporaryDirectory(prefix='.comparison-deposit-',dir=output.parent) as temporary:
        staged=Path(temporary)/'deposit'
        staged.mkdir()
        archives={name+'.tar.xz':pack(staged/(name+'.tar.xz'),files) for name,files in groups.items()}
        result=dict(schema_version=1,status='complete',workflow_version=__version__,
            source_commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=root,text=True).strip(),
            archives=archives,scope='Completed phases 0–4: processed inputs, five supervised formulations, objective comparators and figure inputs',
            original_artifacts='Immutable original summary manifests and run definitions retain their recorded method sets',
            omitted_intermediates='Full inner candidate predictions can be regenerated by rerunning selection',
            supplemental_status='Learning curves and deployment are distributed as a separate deposit after completion')
        write_json(staged/'manifest.json',result)
        verify_archive(staged)
        staged.rename(output)
    return result


def portable(name):
    p=Path(name)
    if not name or p.is_absolute() or '..' in p.parts or '\\' in name or name!=p.as_posix():
        raise ValueError('Unsafe archive member path')
    return p


def pack(path,files):
    inventory={}
    with tarfile.open(path,'w:xz',preset=6) as archive:
        for name,source in sorted(files.items()):
            portable(name)
            data=source if isinstance(source,bytes) else Path(source).read_bytes()
            info=tarfile.TarInfo(name)
            info.size=len(data)
            info.mtime=0
            info.mode=0o644
            archive.addfile(info,io.BytesIO(data))
            inventory[name]=dict(sha256=hashlib.sha256(data).hexdigest(),bytes=len(data))
    if Path(path).stat().st_size>=90*1024**2:
        raise ValueError('Split the deposit: individual archives must stay below 90 MiB')
    return dict(sha256=sha256(path),bytes=Path(path).stat().st_size,files=inventory)


def verify_archive(folder):
    folder=Path(folder)
    manifest=json.loads((folder/'manifest.json').read_text())
    if manifest.get('status')!='complete' or manifest.get('schema_version')!=1 or not manifest.get('archives'):
        raise ValueError('Expected a complete benchmark deposit')
    for name,metadata in manifest['archives'].items():
        if len(portable(name).parts)!=1 or sha256(folder/name)!=metadata['sha256']:
            raise ValueError('Archive container identity differs')
        found=set()
        with tarfile.open(folder/name,'r:xz') as archive:
            for member in archive:
                portable(member.name)
                if not member.isfile() or member.name in found or member.name not in metadata['files']:
                    raise ValueError('Unexpected, linked or duplicate archive member')
                expected=metadata['files'][member.name]
                if member.size!=expected['bytes'] or member.size>1024**3:
                    raise ValueError('Archive member size differs')
                stream=archive.extractfile(member)
                digest=hashlib.sha256()
                for block in iter(lambda:stream.read(1024**2),b''): digest.update(block)
                if digest.hexdigest()!=expected['sha256']: raise ValueError('Archive member SHA-256 mismatch')
                found.add(member.name)
        if found!=set(metadata['files']): raise ValueError('Incomplete archive inventory')
    return manifest


def restore(folder,root):
    folder,root=Path(folder).resolve(),Path(root).resolve()
    manifest=verify_archive(folder)
    # Preflight every destination before writing any file.
    for metadata in manifest['archives'].values():
        for name,identity in metadata['files'].items():
            path=(root/portable(name)).resolve()
            if not path.is_relative_to(root): raise ValueError('Extraction path escapes destination')
            if path.exists() and (not path.is_file() or sha256(path)!=identity['sha256']):
                raise ValueError(f'Refusing to replace a different existing file: {name}')
    written=0
    for name in manifest['archives']:
        with tarfile.open(folder/name,'r:xz') as archive:
            for member in archive:
                path=root/portable(member.name)
                if path.exists(): continue
                path.parent.mkdir(parents=True,exist_ok=True)
                path.write_bytes(archive.extractfile(member).read())
                written+=1
    return written


def build_archive(pipeline, output):
    """Package only completed fixed-AMIGA evidence; phase 0–4 have their own deposit."""
    pipeline, output = Path(pipeline).resolve(), Path(output).resolve()
    if json.loads((pipeline / 'state.json').read_text())['status'] != 'complete' or output.exists():
        raise ValueError('Require a complete pipeline and a new deposit destination')
    manifest, c, jobs = read_run(pipeline / 'run')
    root = Path(manifest['repo_root'])
    verify_sources(root, c)
    for stage in ('summary', 'application'):
        verify_manifest(pipeline / stage / 'manifest.json')
    groups = {name: {} for name in ('inputs', 'summary', 'learning-BIO-INSIGHT',
                                    'learning-MO-GENECI', 'application')}

    def add(group, path):
        path = Path(path)
        groups[group][path.relative_to(root).as_posix()] = path

    for info in c['original']['split_contract']['cases'].values():
        add('inputs', root / info['data_path'])
    for name in ('contract.json', 'plan.json', 'manifest.json', 'state.json'):
        add('summary', pipeline / 'run' / name)
    add('summary', pipeline / 'state.json')
    for folder in ('summary', 'application'):
        for path in (pipeline / folder).rglob('*'):
            if path.is_file():
                add(folder, path)
    for job in jobs:
        complete = completed_job(pipeline / 'run', job)
        if complete is None:
            raise ValueError('Incomplete AMIGA fit')
        _, directory = complete
        group = 'application' if job['context_id'] == 'deployment' else 'learning-' + job['case']
        for path in directory.iterdir():
            if path.is_file() and path.name != 'worker.log':
                add(group, path)
    case = root / 'experiments/BIO-INSIGHT/real-world/tcga_brca'
    add('application', case / 'amiga/data_real.csv')
    for path in (case / 'bioinsight').glob('*/lists/GRN_*.csv'):
        add('application', path)
    output.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix='.amiga-deposit-', dir=output.parent) as temporary:
        staged = Path(temporary) / 'deposit'
        staged.mkdir()
        archives = {name+'.tar.xz': pack(staged / (name+'.tar.xz'), files) for name, files in groups.items()}
        result = dict(schema_version=1, status='complete', workflow_version=__version__,
            source_commit=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip(),
            supplementary_contract_sha256=sha256(pipeline / 'run/contract.json'), archives=archives,
            scope='Fixed-AMIGA learning curves, original five-selector TCGA analysis and prediction-only timing',
            benchmark_reference='amiga-exp-benchmarks-v0.3.0; completed phase 0–4 evidence remains unchanged',
            resource_terms='External regulatory evidence retains its original attribution and terms')
        write_json(staged / 'manifest.json', result)
        verify_archive(staged)
        staged.rename(output)
    return result
